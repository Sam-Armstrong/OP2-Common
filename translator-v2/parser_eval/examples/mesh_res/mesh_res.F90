! Unstructured edge residual on a triangle mesh for OP2 parser evaluation.
! Uses airfoil-style dual maps: edge->nodes (geometry) and edge->cells
! (indirect INC). Mesh is generated by triangulating an Nx x Ny lattice.

program mesh_res
    use OP2_FORTRAN_DECLARATIONS
    use OP2_FORTRAN_REFERENCE

    use, intrinsic :: ISO_C_BINDING

    implicit none

    ! ~7.2M triangles / ~10.8M edges; sized for ~10-30s on c_cuda
    integer(4), parameter :: nx = 1900
    integer(4), parameter :: ny = 1900
    integer(4), parameter :: nnode = (nx + 1) * (ny + 1)
    integer(4), parameter :: ncell = 2 * nx * ny
    integer(4), parameter :: niter = 700
    real(8), parameter :: tolerance = 1.0d-6

    integer(4) :: i, j, n, c, e, nedge
    integer(4) :: n0, n1, n2, n3
    integer(4) :: c_bl, c_br, c_tl, c_tr
    integer(4), dimension(:), allocatable :: ecell, edge, cell
    real(8), dimension(:), allocatable :: q, res, x

    real(8) :: eps, residual, q_max, q_sum

    type(op_set) :: nodes, cells, edges
    type(op_map) :: pecell, pedge, pcell
    type(op_dat) :: p_q, p_res, p_x

    call op_init(0)

    allocate(ecell(2 * (3 * nx * ny)))
    allocate(edge(2 * (3 * nx * ny)))
    allocate(cell(3 * ncell))
    allocate(q(ncell))
    allocate(res(ncell))
    allocate(x(2 * nnode))

    do j = 0, ny
        do i = 0, nx
            n = i + j * (nx + 1) + 1
            x(2 * (n - 1) + 1) = real(i, 8) / real(nx, 8)
            x(2 * (n - 1) + 2) = real(j, 8) / real(ny, 8)
        end do
    end do

    c = 1
    do j = 0, ny - 1
        do i = 0, nx - 1
            n0 = i + j * (nx + 1) + 1
            n1 = (i + 1) + j * (nx + 1) + 1
            n2 = (i + 1) + (j + 1) * (nx + 1) + 1
            n3 = i + (j + 1) * (nx + 1) + 1

            cell(3 * (c - 1) + 1) = n0
            cell(3 * (c - 1) + 2) = n1
            cell(3 * (c - 1) + 3) = n2
            c = c + 1

            cell(3 * (c - 1) + 1) = n0
            cell(3 * (c - 1) + 2) = n2
            cell(3 * (c - 1) + 3) = n3
            c = c + 1
        end do
    end do

    ! each interior interface stores both the two cells and the two nodes
    e = 1
    do j = 0, ny - 1
        do i = 0, nx - 1
            n0 = i + j * (nx + 1) + 1
            n1 = (i + 1) + j * (nx + 1) + 1
            n2 = (i + 1) + (j + 1) * (nx + 1) + 1
            n3 = i + (j + 1) * (nx + 1) + 1

            c_bl = 2 * (i + j * nx) + 1
            c_tl = c_bl + 1

            ! diagonal n0--n2 between the two triangles of this quad
            edge(2 * (e - 1) + 1) = n0
            edge(2 * (e - 1) + 2) = n2
            ecell(2 * (e - 1) + 1) = c_bl
            ecell(2 * (e - 1) + 2) = c_tl
            e = e + 1

            if (i < nx - 1) then
                c_br = 2 * ((i + 1) + j * nx) + 1
                edge(2 * (e - 1) + 1) = n1
                edge(2 * (e - 1) + 2) = n2
                ecell(2 * (e - 1) + 1) = c_bl
                ecell(2 * (e - 1) + 2) = c_br
                e = e + 1
            end if

            if (j < ny - 1) then
                c_tr = 2 * (i + (j + 1) * nx) + 2
                edge(2 * (e - 1) + 1) = n2
                edge(2 * (e - 1) + 2) = n3
                ecell(2 * (e - 1) + 1) = c_tl
                ecell(2 * (e - 1) + 2) = c_tr
                e = e + 1
            end if
        end do
    end do
    nedge = e - 1

    q = 0.0_8
    q(ncell / 2) = 1.0_8
    res = 0.0_8

    call op_decl_set(nnode, nodes, "nodes")
    call op_decl_set(ncell, cells, "cells")
    call op_decl_set(nedge, edges, "edges")

    call op_decl_map(edges, nodes, 2, edge, pedge, "pedge")
    call op_decl_map(edges, cells, 2, ecell, pecell, "pecell")
    call op_decl_map(cells, nodes, 3, cell, pcell, "pcell")

    call op_decl_dat(nodes, 2, "real(8)", x, p_x, "p_x")
    call op_decl_dat(cells, 1, "real(8)", q, p_q, "p_q")
    call op_decl_dat(cells, 1, "real(8)", res, p_res, "p_res")

    deallocate(ecell)
    deallocate(edge)
    deallocate(cell)
    deallocate(q)
    deallocate(res)
    deallocate(x)

    eps = 0.20_8
    call op_decl_const(eps, 1, "real(8)")

    call op_profile_start("MESH_RES")

    do i = 1, niter
        call op_par_loop_6(res_calc, edges, &
            op_arg_dat(p_x,   1, pedge,  2, "real(8)", OP_READ), &
            op_arg_dat(p_x,   2, pedge,  2, "real(8)", OP_READ), &
            op_arg_dat(p_q,   1, pecell, 1, "real(8)", OP_READ), &
            op_arg_dat(p_q,   2, pecell, 1, "real(8)", OP_READ), &
            op_arg_dat(p_res, 1, pecell, 1, "real(8)", OP_INC),  &
            op_arg_dat(p_res, 2, pecell, 1, "real(8)", OP_INC))

        residual = 0.0_8
        q_max = 0.0_8

        call op_par_loop_7(update, cells, &
            op_arg_dat(p_x,    1, pcell, 2, "real(8)", OP_READ), &
            op_arg_dat(p_x,    2, pcell, 2, "real(8)", OP_READ), &
            op_arg_dat(p_x,    3, pcell, 2, "real(8)", OP_READ), &
            op_arg_dat(p_q,   -1, OP_ID, 1, "real(8)", OP_RW), &
            op_arg_dat(p_res, -1, OP_ID, 1, "real(8)", OP_RW), &
            op_arg_gbl(residual, 1, "real(8)", OP_INC), &
            op_arg_gbl(q_max, 1, "real(8)", OP_MAX))
    end do

    call op_profile_end()

    allocate(q(ncell))
    call op_fetch_data(p_q, q)

    q_sum = sum(q)
    if (abs(q_sum - 1.0_8) < tolerance .and. maxval(q) > 0.0_8 .and. maxval(q) <= 1.0_8 + tolerance) then
        write(*, "(A,I0,A,I0,A,ES12.5,A,ES12.5)") &
            "mesh_res ok: ncell=", ncell, " nedge=", nedge, " sum(q)=", q_sum, " q_max=", maxval(q)
        print *, "Test PASSED"
    else
        write(*, "(A,ES12.5,A,ES12.5)") "mesh_res fail: sum(q)=", q_sum, " q_max=", maxval(q)
        print *, "Test FAILED"
    end if

    deallocate(q)
    call op_exit()

contains

    subroutine edge_contrib(x1, x2, q1, q2, flux)
        implicit none
        real(8), dimension(2), intent(in) :: x1, x2
        real(8), intent(in) :: q1, q2
        real(8), intent(out) :: flux
        integer(4), parameter :: burn = 64
        integer(4) :: k
        real(8) :: dx, dy, len, damp

        dx = x2(1) - x1(1)
        dy = x2(2) - x1(2)
        len = sqrt(dx * dx + dy * dy) + 1.0d-30
        flux = eps * (q2 - q1) * len

        ! dependent recurrence so the compiler cannot fold the burn away
        damp = 1.0_8
        do k = 1, burn
            damp = 0.5_8 * damp + 0.5_8 / (1.0_8 + abs(flux) * damp)
        end do
        flux = flux * (damp / (damp + 1.0d-30)) * ((damp + 1.0d-30) / damp)
    end subroutine

    subroutine res_calc(x1, x2, q1, q2, res1, res2)
        implicit none
        real(8), dimension(2), intent(in) :: x1, x2
        real(8), intent(in) :: q1, q2
        real(8), intent(inout) :: res1, res2
        real(8) :: flux

        call edge_contrib(x1, x2, q1, q2, flux)
        res1 = res1 + flux
        res2 = res2 - flux
    end subroutine

    subroutine update(x1, x2, x3, q, res, residual, q_max)
        implicit none
        real(8), dimension(2), intent(in) :: x1, x2, x3
        real(8), intent(inout) :: q, res, residual, q_max
        real(8) :: area2

        area2 = abs((x2(1) - x1(1)) * (x3(2) - x1(2)) - (x3(1) - x1(1)) * (x2(2) - x1(2)))
        q = q + res
        residual = residual + abs(res) * (1.0_8 + area2)
        res = 0.0_8
        q_max = max(q_max, q)
    end subroutine

end program
